"""Speech generation and management API endpoints"""
from typing import List, Optional
from uuid import UUID
from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.database import get_db
from app.models_extended import SpeechDraft, BilingualSpeech, SpeechMaterial
from pydantic import BaseModel, Field

router = APIRouter(prefix="/api/v1/speech", tags=["speech"])


# Pydantic schemas
class SpeechGenerateRequest(BaseModel):
    """Request schema for generating speech drafts"""
    topic: str = Field(..., description="Speech topic/title")
    template_type: str = Field(..., description="Template: ted_talk/toastmasters/elevator_pitch/storytelling")
    key_points: List[str] = Field(..., description="Key points to include in speech")
    target_duration: Optional[int] = Field(None, description="Target duration in minutes (template default used if not specified)")
    audience: Optional[str] = Field(None, description="Target audience description")
    tone: Optional[str] = Field("inspirational", description="Speech tone: inspirational/educational/persuasive/motivational")


class SpeechDraftResponse(BaseModel):
    """Response schema for speech drafts"""
    id: UUID
    user_id: UUID
    topic: str
    template_type: str
    estimated_duration: Optional[int]
    draft_json: Optional[dict]
    full_speech: Optional[str]
    speaker_notes: Optional[str]
    related_insights: Optional[list]
    status: str
    feedback_score: Optional[float]
    delivered_at: Optional[datetime]
    created_at: datetime

    class Config:
        from_attributes = True


class BilingualSpeechResponse(BaseModel):
    """Response schema for bilingual speeches"""
    id: UUID
    user_id: UUID
    speech_draft_id: UUID
    primary_language: Optional[str]
    secondary_language: Optional[str]
    bilingual_version: Optional[dict]
    switching_cues: Optional[list]
    translation_quality: Optional[float]
    naturalness_score: Optional[float]
    created_at: datetime

    class Config:
        from_attributes = True


class SpeechMaterialResponse(BaseModel):
    """Response schema for speech materials"""
    id: UUID
    title: str
    material_type: str
    content: str
    source_url: Optional[str]
    domain: Optional[str]
    tags: Optional[list]
    usage_count: int
    created_at: datetime

    class Config:
        from_attributes = True


@router.post("/generate", response_model=SpeechDraftResponse, status_code=status.HTTP_201_CREATED)
async def generate_speech(
    request: SpeechGenerateRequest,
    db: Session = Depends(get_db)
):
    """
    Generate a speech draft using international templates
    
    This endpoint creates a structured speech draft based on the selected template:
    
    - **TED Talk** (~18 min, 5 sections): Hook → Problem → Solution → Evidence → Call to Action
    - **Toastmasters** (~7 min, 5 sections): Opening → Point 1 → Point 2 → Point 3 → Closing
    - **Elevator Pitch** (~1 min, 4 sections): Who → What → Why → Ask
    - **Hero's Journey** (~15 min, 12 sections): Complete narrative arc with transformation
    
    The speech is generated by:
    1. Selecting appropriate template structure
    2. Organizing key points into sections
    3. Generating engaging content for each section
    4. Adding transitions and rhetorical devices
    5. Creating speaker notes and timing guidance
    
    Related knowledge insights are automatically incorporated to enrich the content.
    """
    # Get template structure
    template = get_template_structure(request.template_type, request.target_duration)
    
    # TODO: Integrate LLM for content generation
    # For now, create a basic structure
    draft_content = {
        "template": request.template_type,
        "topic": request.topic,
        "audience": request.audience,
        "tone": request.tone,
        "sections": [],
        "estimated_duration": template["duration"]
    }
    
    # Create sections based on template
    for i, section in enumerate(template["sections"], 1):
        section_content = {
            "section_number": i,
            "section_name": section["name"],
            "description": section["description"],
            "estimated_time": section["time"],
            "key_points": request.key_points[:2],  # TODO: Distribute key points intelligently
            "content": f"[Content for {section['name']} - TO BE GENERATED]"  # Placeholder
        }
        draft_content["sections"].append(section_content)
    
    # Generate full speech text (placeholder)
    full_speech = generate_full_speech_text(draft_content)
    
    # Create speaker notes
    speaker_notes = generate_speaker_notes(draft_content)
    
    # Find related insights
    related_insights = []  # TODO: Query knowledge base for related insights
    
    # Create speech draft
    speech = SpeechDraft(
        user_id=UUID("00000000-0000-0000-0000-000000000001"),  # TODO: Get from JWT auth
        topic=request.topic,
        template_type=request.template_type,
        estimated_duration=template["duration"],
        draft_json=draft_content,
        full_speech=full_speech,
        speaker_notes=speaker_notes,
        related_insights=related_insights,
        status="draft"
    )
    
    db.add(speech)
    db.commit()
    db.refresh(speech)
    
    return speech



@router.get("/bilingual/{speech_id}", response_model=BilingualSpeechResponse)
async def get_bilingual_speech(
    speech_id: UUID,
    db: Session = Depends(get_db)
):
    """
    Get bilingual version of a speech (Chinese-English)

    This endpoint retrieves the bilingual version of a speech draft, which includes:
    - Original Chinese text
    - English translation
    - Polished version (if available)
    - Translation quality score

    If the bilingual version doesn't exist, it can be generated via the translation service.
    """
    bilingual = db.query(BilingualSpeech).filter(BilingualSpeech.speech_draft_id == speech_id).first()
    if not bilingual:
        raise HTTPException(status_code=404, detail="Bilingual speech not found. Please generate translation first.")
    return bilingual


@router.get("/{speech_id}", response_model=SpeechDraftResponse)
async def get_speech_draft(
    speech_id: UUID,
    db: Session = Depends(get_db)
):
    """Get a specific speech draft by ID"""
    speech = db.query(SpeechDraft).filter(SpeechDraft.id == speech_id).first()
    if not speech:
        raise HTTPException(status_code=404, detail="Speech draft not found")
    return speech

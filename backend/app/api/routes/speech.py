def generate_full_speech_text(draft_content: dict) -> str:
    """Generate full speech text from draft structure"""
    lines = []
    lines.append(f"# {draft_content['topic']}")
    lines.append(f"**Template:** {draft_content['template']}")
    lines.append(f"**Duration:** ~{draft_content['estimated_duration']} minutes\n")
    
    for section in draft_content['sections']:
        lines.append(f"## {section['section_name']} ({section['estimated_time']} min)")
        lines.append(section['content'])
        lines.append("")
    
    return "\n".join(lines)


def generate_speaker_notes(draft_content: dict) -> str:
    """Generate speaker notes with delivery tips"""
    notes = []
    notes.append("Speaker Notes:")
    notes.append("=" * 50)
    notes.append("")
    
    for section in draft_content['sections']:
        notes.append(f"{section['section_name']}:")
        notes.append(f"  - Estimated time: {section['estimated_time']} min")
        notes.append(f"  - Focus: {section['description']}")
        notes.append(f"  - Tip: Maintain eye contact, use gestures, vary tone")
        notes.append("")
    
    notes.append("General Tips:")
    notes.append("- Practice at least 3 times before delivery")
    notes.append("- Time yourself to stay within limits")
    notes.append("- Prepare for Q&A after the speech")
    notes.append("- Record yourself for self-review")
    
    return "\n".join(notes)


@router.get("/", response_model=List[SpeechDraftResponse])
async def list_speeches(
    template_type: Optional[str] = None,
    status_filter: Optional[str] = None,
    limit: int = 20,
    offset: int = 0,
    db: Session = Depends(get_db)
):
    """
    List speech drafts with optional filtering

    Query parameters:
    - template_type: Filter by template (ted_talk/toastmasters/elevator_pitch/storytelling)
    - status: Filter by status (draft/reviewed/delivered/archived)
    - limit: Number of results (default 20, max 100)
    - offset: Pagination offset
    """
    query = db.query(SpeechDraft)

    if template_type:
        query = query.filter(SpeechDraft.template_type == template_type)
    if status_filter:
        query = query.filter(SpeechDraft.status == status_filter)

    speeches = query.order_by(SpeechDraft.created_at.desc()).offset(offset).limit(limit).all()
    return speeches


@router.get("/materials/search", response_model=List[SpeechMaterialResponse])
async def search_materials(
    query: str,
    domain: Optional[str] = None,
    material_type: Optional[str] = None,
    limit: int = 10,
    db: Session = Depends(get_db)
):
    """
    Search speech materials by keyword

    Query parameters:
    - query: Search term (searches title and content)
    - domain: Filter by domain (AI/marketing/chinese_classics/etc.)
    - material_type: Filter by type (quote/story/statistic/metaphor)
    - limit: Number of results (default 10, max 50)
    """
    from sqlalchemy import or_

    materials_query = db.query(SpeechMaterial).filter(
        or_(
            SpeechMaterial.title.ilike(f"%{query}%"),
            SpeechMaterial.content.ilike(f"%{query}%")
        )
    )

    if domain:
        materials_query = materials_query.filter(SpeechMaterial.domain == domain)
    if material_type:
        materials_query = materials_query.filter(SpeechMaterial.material_type == material_type)

    materials = materials_query.order_by(SpeechMaterial.usage_count.desc()).limit(limit).all()
    return materials


